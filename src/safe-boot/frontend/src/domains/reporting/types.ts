/**
 * Generic pagination response.
 */
export interface PaginatedResponse<T> {
  readonly items: ReadonlyArray<T>;
  readonly totalCount: number;
  readonly hasNextPage: boolean;
}

/**
 Report with generated data preview.
 */
export interface ReportInstanceWithPreview {
  /** The report instance. */
  readonly report: ReportGenerated;

  /** Preview of generated data (first 500 chars). */
  readonly preview: string;
}

/**
 Aggregated structure returned by useReports().
 */
export interface ReportsDomainModel {
  /** Report definitions. */
  readonly definitions: ReadonlyArray<ReportDefinition>;

  /** Generated report instances. */
  readonly instances: ReadonlyArray<ReportInstanceWithPreview>;

  /** Total count matching filters. */
  readonly totalCount: number;

  /** Currently selected report (if any). */
  readonly selectedReport: ReportGenerated | null;

  /** Loading state. */
  readonly isLoading: boolean;

  /** Error state (if any). */
  readonly error: string | null;
}

/**
 Aggregated structure returned by useReportSnapshot().
 */
export interface ReportSnapshotDomainModel {
  /** The snapshot. */
  readonly snapshot: ReportSnapshot | null;

  /** Loading state. */
  readonly isLoading: boolean;

  /** Error state (if any). */
  readonly error: string | null;
}

