/**
 * Report type.
 */
export type ReportType = 'balance_sheet' | 'income_statement' | 'cash_flow' | 'ledger' | 'custom';

/**
 * Report period type.
 */
export type ReportPeriod = 'daily' | 'weekly' | 'monthly' | 'quarterly' | 'yearly';

/* ------------------------------------------------------------------ */
/*  Entities                                                           */
/* ------------------------------------------------------------------ */

/**
 * ReportDefinition — template for generating reports.
 * Maps to physical table `report_templates` in POSTGRESQL-SCHEMA-PACK-v1.md.
 */
export interface ReportDefinition {
  /** Universally unique identifier for this report definition. */
  readonly id: string;

  /** Organization this report belongs to. */
  readonly organizationId: string;

  /** Report code/key (e.g., 'balance-sheet', 'income-statement'). */
  readonly code: string;

  /** Report title. */
  readonly title: string;

  /** Report description. */
  readonly description: string;

  /** Report type. */
  readonly type: ReportType;

  /** Default period (monthly by default). */
  readonly defaultPeriod: ReportPeriod;

  /** Whether this is a system report. */
  readonly isSystem: boolean;

  /** Version for optimistic locking. */
  readonly version: number;

  /** Whether this record is synced with the server. */
  readonly synced: boolean;

  /** Timestamp when this record was created (UTC ISO 8601). */
  readonly createdAt: string;

  /** Timestamp of last modification (UTC ISO 8601). */
  readonly updatedAt: string;
}

/**
 * ReportGenerated — an generated report instance.
 */
export interface ReportGenerated {
  /** Universally unique identifier for this report instance. */
  readonly id: string;

  /** Reference to the report definition. */
  readonly reportDefinitionId: string;

  /** Organization this report belongs to. */
  readonly organizationId: string;

  /** Report generation period start date. */
  readonly periodStart: string;

  /** Report generation period end date. */
  readonly periodEnd: string;

  /** Report period type. */
  readonly period: ReportPeriod;

  /** Report type. */
  readonly type: ReportType;

  /** Generated data (JSON). */
  readonly data: Record<string, unknown>;

  /** Report status (draft, generated, failed, archived). */
  readonly status: 'draft' | 'generated' | 'failed' | 'archived';

  /** Generated by user ID. */
  readonly generatedBy: string;

  /** Generation timestamp. */
  readonly generatedAt: string;

  /** Expiration timestamp (if applicable). */
  readonly expiresAt: string | null;

  /** Version for optimistic locking. */
  readonly version: number;

  /** Whether this record is synced with the server. */
  readonly synced: boolean;

  /** Timestamp when this record was created (UTC ISO 8601). */
  readonly createdAt: string;

  /** Timestamp of last modification (UTC ISO 8601). */
  readonly updatedAt: string;
}

/**
 * ReportSnapshot — a snapshot of financial data at a point in time.
 */
export interface ReportSnapshot {
  /** Universally unique identifier for this snapshot. */
  readonly id: string;

  /** Organization this snapshot belongs to. */
  readonly organizationId: string;

  /** Snapshot date (UTC). */
  readonly snapshotDate: string;

  /** Financial metrics. */
  readonly metrics: Record<string, number>;

  /** Currency snapshot. */
  readonly currency: string;

  /** Version for optimistic locking. */
  readonly version: number;

  /** Whether this record is synced with the server. */
  readonly synced: boolean;

  /** Timestamp when this record was created (UTC ISO 8601). */
  readonly createdAt: string;

  /** Timestamp of last modification (UTC ISO 8601). */
  readonly updatedAt: string;
}

